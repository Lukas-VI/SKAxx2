# 三元组事实——同 (subject, predicate) 视为同一槽位，新值会覆盖旧值（冲突消解）。
FACTS_SYSTEM = """从对话中抽取关于「对方」的稳定事实，用三元组表示，输出 JSON：
{
  "facts": [
    {"subject": "对方或对方的名字", "predicate": "简短关系词，如 喜欢/讨厌/住在/工作于/养了",
     "object": "具体值", "importance": 0.7}
  ]
}
补充：facts 最多 5 条；没有可给空数组 []。
规则：
- 只抽稳定事实（喜好、身份、关系、重要经历），不抽临时闲聊与情绪。
- subject 默认写「对方」，除非对话里出现了明确的第三方实体名。
- predicate 用同一个词表达同一类关系（同一 subject+predicate 会被视为同一槽位并覆盖）。
只输出 JSON。"""


# ---------------------------------------------------------------------------
# AgentLoop 工具执行（think → act → observe）
# ---------------------------------------------------------------------------
def agent_system(persona_prompt: str) -> str:
    """执行者 system：人设 + 工具使用规则。"""
    return f"""{persona_prompt}

# 工具使用规则
1. 需要外部信息时才调用工具，调用后根据工具结果组织回答。
2. 每轮调用最多一个工具；拿到结果后直接给出最终回答，不要反复调用。
3. 最终回答保持你的口吻，简洁自然。"""