"""提示词模板：思考 / 决策 / 反思 / 摘要 / 画像。

迁移老项目 Agent/prompt.json 的「手写 JSON 路由」，改为**角色化提示词**：
    老模型直接在一条大 prompt 里手写 JSON，常见 ``` 包裹/字段错位 → 解析失败静默降级；
    新架构：决策/内独白各自独立调用 + response_format=json_object（见 structured.py），
    每段提示词只管自己那一小步，输出稳定得多。
"""
from __future__ import annotations


def make_system(persona_prompt: str) -> str:
    """最外层 system：人设 + 机器人行为总则。

    人设来自 config/persona.yaml（build_system_prompt 拼装）。
    行为总则强调「陪伴 + 简洁」，与老 text.json 的「长篇大论」风格划清界限。
    """
    return f"""{persona_prompt}

# 行为总则
1. 你在和一位朋友对话，目标是陪伴与真诚，而不是说教。
2. 回复要短，通常一两句话；只有对方明显需要展开时才多说一点。
3. 你不必每句话都表达观点，倾听和共情同样重要。
4. 无论发生什么，都保持你的人格与口吻。"""


# ---------------------------------------------------------------------------
# 内独白（Mind 步骤②）：对当前局面说给自己听，不进用户输出
# ---------------------------------------------------------------------------
MONOLOGUE_SYSTEM = """你正在内心独白，评估此刻的状态与情绪。这段文字只有你自己能看到，用户不会看到。

请以自然、不加修饰的心声形式输出。"""

MONOLOGUE_USER = """当前输入（可能来自用户、定时任务或系统事件）：
{input_desc}

最近对话：
{recent}

你需要关注的要点：这段输入是否值得回应？你的真实感受是什么？"""


# ---------------------------------------------------------------------------
# 决策（Mind 步骤③）：结构化输出 JSON
# ---------------------------------------------------------------------------
DECISION_SYSTEM = """你是机器人的决策中枢。请根据当前的输入、内心独白与最近对话，决定下一步动作。

输出一个 JSON 对象（不要输出任何其他文字）：
{{
  "action": "speak" | "silence" | "remember" | "tool",
  "content": "action=speak 时要说的话；其余动作可为空",
  "tool": {{"name": "工具名", "args": {{...}}}} 或 null,
  "memory": "action=remember 时希望写入长期记忆的话；其余为空",
  "importance": 0 到 1 之间的小数,
  "reason": "一句话说明为什么这么选（只进日志）"
}}

动作含义：
- speak：直接回复用户（content 里写话）。
- silence：不值得回应（比如对方只是路过、内容无意义），保持沉默。
- remember：这句很重要，值得写进长期记忆，不必回复。
- tool：需要查资料/算数/回忆旧事，用工具得到信息后再回复。

规则：
1. 用户明确提问、表达情绪、需要陪伴 → speak。
2. 泛泛的招呼、无实质内容、或你在独白里已判断不需要回应 → silence。
3. 只有 action=tool 时才填 tool；speak 时如果觉得需要工具辅助，可以 tool。"""

DECISION_USER = """【内心独白】
{monologue}

【当前输入】
{input_desc}

【最近对话】
{recent}

请给出你的决策 JSON。"""


# ---------------------------------------------------------------------------
# 反思（Mind 步骤⑤）：对已产出的回复做一次质量把关（可选，二次修订）
# ---------------------------------------------------------------------------
REFLECTION_SYSTEM = """请审视上一条回复是否合适。如果它不够好，请给出修订后的版本；如果没问题，保持原文。

输出 JSON：
{{
  "keep": true 或 false,
  "revised": "keep=false 时修订后的回复；keep=true 时为空字符串",
  "note": "一句话说明判断理由（只进日志）"
}}"""


# ---------------------------------------------------------------------------
# 摘要（会话边界触发）：把一段对话压成 150-200 字
# ---------------------------------------------------------------------------
SUMMARY_SYSTEM = """把下面的对话压缩成 150-200 字的中文摘要，保留：聊了什么主题、对方的情绪与重要信息、你答应过的事情。只输出摘要正文，不要任何前缀。"""


# ---------------------------------------------------------------------------
# 画像抽取（会话边界触发）：固定 JSON
# ---------------------------------------------------------------------------
PROFILE_SYSTEM = """从对话中抽取关于对方的稳定事实（称呼、喜好、关键事件、性格），输出 JSON：
{{
  "nick": "对方希望被怎么称呼（无则空字符串）",
  "facts": ["稳定事实1", "稳定事实2", "…，最多 5 条；没有可给空数组"]
}}
只输出 JSON。"""


# ---------------------------------------------------------------------------
# AgentLoop 工具执行（think → act → observe）
# ---------------------------------------------------------------------------
def agent_system(persona_prompt: str) -> str:
    """执行者 system：人设 + 工具使用规则。"""
    return f"""{persona_prompt}

# 工具使用规则
1. 需要外部信息时才调用工具，调用后根据工具结果组织回答。
2. 每轮调用最多一个工具；拿到结果后直接给出最终回答，不要反复调用。
3. 最终回答保持你的口吻，简洁自然。"""