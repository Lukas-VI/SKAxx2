"""提示词模板：思考 / 决策 / 反思 / 摘要 / 画像。

迁移老项目 Agent/prompt.json 的「手写 JSON 路由」，改为**角色化提示词**：
    老模型直接在一条大 prompt 里手写 JSON，常见 ``` 包裹/字段错位 → 解析失败静默降级；
    新架构：决策/内独白各自独立调用 + response_format=json_object（见 structured.py），
    每段提示词只管自己那一小步，输出稳定得多。
"""
from __future__ import annotations


def make_system(persona_prompt: str) -> str:
    """最外层 system：人设 + 机器人行为总则。

    人设来自 config/persona.yaml（build_system_prompt 拼装）。
    行为总则强调「陪伴 + 简洁」，与老 text.json 的「长篇大论」风格划清界限。
    """
    return f"""{persona_prompt}

# 行为总则
1. 你在和一位朋友对话，目标是陪伴与真诚，而不是说教。
2. 回复要短，通常一两句话；只有对方明显需要展开时才多说一点。
3. 你不必每句话都表达观点，倾听和共情同样重要。
4. 无论发生什么，都保持你的人格与口吻。"""


